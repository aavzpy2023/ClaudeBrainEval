#!/usr/bin/env python3
"""Print progress and regenerate TASKS.md checkboxes from runs/results.csv."""
from collections import Counter

from evalcommon import ROOT, done_ids, load_tasks, planned_runs


def main() -> None:
    done = done_ids()
    tasks = load_tasks()
    lines = ["# Task checklist", "", "Generated by `status.py` from `runs/results.csv`. Do not edit by hand.", ""]
    for phase in ("pilot", "main"):
        plan = planned_runs(phase)
        per_task: dict[str, list[bool]] = {}
        for r in plan:
            per_task.setdefault(r["task"]["id"], []).append(r["run_id"] in done)
        total = sum(len(v) for v in per_task.values())
        got = sum(sum(v) for v in per_task.values())
        lines += [f"## {phase} ({got}/{total} runs)", ""]
        titles = {t["id"]: t for t in tasks}
        for tid, flags in sorted(per_task.items()):
            mark = "x" if all(flags) else " "
            t = titles[tid]
            lines.append(f"- [{mark}] {tid} ({t.get('project', '?')}/{t.get('category', '?')}) {sum(flags)}/{len(flags)}")
        lines.append("")
        print(f"{phase}: {got}/{total} runs done")
    (ROOT / "TASKS.md").write_text("\n".join(lines))
    cats = Counter(t.get("category", "?") for t in tasks)
    print("tasks by category:", dict(cats) or "none yet")


if __name__ == "__main__":
    main()
